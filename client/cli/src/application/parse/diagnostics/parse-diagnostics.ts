import type {
	NormalizedDocument
} from '@kjvonly/normalized-content';

/** One auditable condition encountered while normalizing a source document. */
export interface ParseWarning {
	/** Stable machine-oriented warning category. */
	readonly code: string;

	/** Human-readable description of the reported source condition. */
	readonly message: string;

	/** Number of equivalent conditions aggregated into this warning. */
	readonly count: number;
}

/**
 * Source-neutral conversion metrics returned with a normalized document.
 *
 * Diagnostics are import-tooling metadata only. They are intentionally kept
 * outside NormalizedDocument so runtime renderers and Domains do not depend on
 * source-conversion concerns.
 */
export interface ParseDiagnostics {
	/** Total normalized blocks produced across the recursive document tree. */
	readonly blocksProduced: number;

	/** Total normalized word units produced. */
	readonly wordsProduced: number;

	/** Number of emitted block/inline-anchor IDs preserved from source HTML. */
	readonly sourceIdsPreserved: number;

	/** Number of emitted block IDs generated by normalization. */
	readonly idsGenerated: number;

	/** Number of normalized words carrying at least one link target. */
	readonly linkedWordsProduced: number;

	/** Aggregated non-fatal source conditions observed during conversion. */
	readonly warnings: readonly ParseWarning[];
}

/** Result returned by the parse application boundary. */
export interface ParseResult {
	/** Canonical validated document suitable for persistence. */
	readonly document: NormalizedDocument;

	/** Import-only report kept outside persisted document content. */
	readonly diagnostics: ParseDiagnostics;
}
