import { describe, expect, it } from 'vitest';

import {
	parseBibleLocationRef
} from './bible-application-reference';

describe('parseBibleLocationRef', () => {
	it.each([
		['1_1', '1_1'],
		['1_1_1', '1_1_1'],
		['1_1_1_5', '1_1_1_5'],
		['1_1_1_0', '1_1_1_0'],
		['50_3_16', '50_3_16'],
		['22_35_10', '22_35_10'],
		['23_119_130', '23_119_130'],
		['72_1_25', '72_1_25'],
		['73_22_21', '73_22_21'],
		['1_1_1-2', '1_1_1-2'],
		['1_1_10-15', '1_1_10-15'],
		['1_1_1-31', '1_1_1-31'],
		['1_1_1-2_0', '1_1_1-2_0'],
		['22_35_10-12', '22_35_10-12'],
		['23_119_130-132', '23_119_130-132'],
		['73_22_20-21', '73_22_20-21']
	])('accepts %s as %s', (source, expected) => {
		expect(parseBibleLocationRef(source)).toBe(expected);
	});

	it.each([
		'', '1', '_1', '1_', '1__1', '1_1__5',
		'1_1_1_1_1', '0_1', '18_1', '74_1', '1_0',
		'1_51', '1_1_0', '1_1_32', '72_2', '73_22_22',
		'1_-1', '+1_1', '1_1.0', '1_1_1.5',
		'01_1', '1_01', '1_1_01', '1_1_1_00',
		'1_1_1_-1', '1_1_1_NaN',
		'9007199254740992_1', '1_9007199254740992',
		'1/1/1', '1/1', '1_1/1',
		'1_1_0-1', '1_1_1-0', '1_1_3-2',
		'1_1_1-32', '1_1_31-32', '22_35_10-17',
		'23_119_130-177', '72_1_25-26',
		'1_1_1-', '1_1_-2', '1_1_1--2', '1_1_1-2-3',
		'1_1_01-2', '1_1_1-02', '1_1_1-2_00',
		'1_1_1-9007199254740992'
	])('rejects invalid payload %s', (value) => {
		expect(parseBibleLocationRef(value)).toBeUndefined();
	});
});
