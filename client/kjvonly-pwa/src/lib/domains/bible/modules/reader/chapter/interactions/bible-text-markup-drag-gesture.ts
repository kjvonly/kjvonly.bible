/** Semantic Bible token visited by a Text Markup drag stroke. */
export interface BibleTextMarkupDragTarget {
	readonly verseNumber: number;
	readonly wordIndex: number;
}

/** Viewport coordinate sample consumed by the DOM-independent gesture state. */
export interface PointerPoint {
	readonly x: number;
	readonly y: number;
}

/** Environment callbacks supplied by the DOM-facing Svelte action. */
interface DragGestureCallbacks {
	/** Maps one viewport point to the Bible token currently under it. */
	readonly resolveTarget: (
		point: PointerPoint
	) => BibleTextMarkupDragTarget | undefined;
	/** Applies the current markup family to a newly visited token. */
	readonly onApply: (
		target: BibleTextMarkupDragTarget
	) => void;
	/** Removes the current markup family from a newly visited token. */
	readonly onRemove: (
		target: BibleTextMarkupDragTarget
	) => void;
	/** Signals that horizontal intent crossed the threshold and became a drag. */
	readonly onDragStart: (
		pointerId: number
	) => void;
	/** Signals completion/cancellation of a drag that had actually started. */
	readonly onDragEnd: (
		pointerId: number
	) => void;
}

const GESTURE_THRESHOLD_PX = 10;
const INTERPOLATION_DISTANCE_PX = 8;
const MAX_INTERPOLATION_STEPS = 48;

/**
 * Owns the transient pointer state for one horizontal Text Markup stroke.
 *
 * The controller is DOM-independent so gesture semantics can be unit tested.
 * Horizontal intent locks the operation once per stroke: rightward applies,
 * leftward removes. Vertical intent cancels tracking and is left to native scroll.
 * Each semantic token is processed at most once per stroke.
 */
export class BibleTextMarkupDragGesture {
	private enabled = false;
	private pointerId: number | undefined;
	private startPoint: PointerPoint | undefined;
	private lastPoint: PointerPoint | undefined;
	private operation: 'apply' | 'remove' | undefined;
	private readonly visitedTargets = new Set<string>();
	private suppressClick = false;

	constructor(
		private readonly callbacks: DragGestureCallbacks
	) {}

	/** Enables/disables gesture eligibility; disabling also cancels active state. */
	setEnabled(enabled: boolean): void {
		this.enabled = enabled;

		if (!enabled) {
			this.cancel();
		}
	}

	/**
	 * Attempts to begin tracking one primary-button pointer.
	 *
	 * @returns `true` only when the pointer starts on a valid Bible token.
	 */
	pointerDown(
		pointerId: number,
		point: PointerPoint,
		isPrimary: boolean,
		button: number
	): boolean {
		if (
			!this.enabled ||
			this.pointerId !== undefined ||
			!isPrimary ||
			button !== 0
		) {
			return false;
		}

		const target =
			this.callbacks.resolveTarget(point);

		if (!target || target.wordIndex < 0) {
			return false;
		}

		this.suppressClick = false;
		this.pointerId = pointerId;
		this.startPoint = point;
		this.lastPoint = point;
		this.operation = undefined;
		this.visitedTargets.clear();
		return true;
	}

	/** Updates gesture intent and paints the segment to the latest pointer sample. */
	pointerMove(
		pointerId: number,
		point: PointerPoint
	): void {
		if (
			pointerId !== this.pointerId ||
			!this.startPoint ||
			!this.lastPoint
		) {
			return;
		}

		if (!this.operation) {
			const deltaX = point.x - this.startPoint.x;
			const deltaY = point.y - this.startPoint.y;
			const horizontalDistance = Math.abs(deltaX);
			const verticalDistance = Math.abs(deltaY);

			if (
				horizontalDistance < GESTURE_THRESHOLD_PX &&
				verticalDistance < GESTURE_THRESHOLD_PX
			) {
				return;
			}

			if (verticalDistance >= horizontalDistance) {
				this.cancel();
				return;
			}

			this.operation =
				deltaX > 0 ? 'apply' : 'remove';
			this.suppressClick = true;
			this.callbacks.onDragStart(pointerId);
		}

		this.processSegment(
			this.lastPoint,
			point
		);
		this.lastPoint = point;
	}

	/** Completes the tracked pointer, preserving click suppression after a drag. */
	pointerUp(pointerId: number): void {
		if (pointerId !== this.pointerId) {
			return;
		}

		this.finish();
	}

	/** Cancels the tracked pointer without suppressing a later unrelated click. */
	pointerCancel(pointerId: number): void {
		if (pointerId !== this.pointerId) {
			return;
		}

		this.suppressClick = false;
		this.finish();
	}

	/**
	 * Consumes the one click generated by a completed drag.
	 *
	 * @returns `true` once when the DOM adapter should swallow that click.
	 */
	consumeSuppressedClick(): boolean {
		if (!this.suppressClick) {
			return false;
		}

		this.suppressClick = false;
		return true;
	}

	/** Returns whether horizontal intent has locked into apply/remove mode. */
	isDragging(): boolean {
		return this.operation !== undefined;
	}

	/** Returns whether this controller currently owns a pointer sequence. */
	isTracking(): boolean {
		return this.pointerId !== undefined;
	}

	/** Clears all transient stroke state and releases an active drag if necessary. */
	cancel(): void {
		if (
			this.pointerId !== undefined &&
			this.operation
		) {
			this.callbacks.onDragEnd(
				this.pointerId
			);
		}

		this.pointerId = undefined;
		this.startPoint = undefined;
		this.lastPoint = undefined;
		this.operation = undefined;
		this.visitedTargets.clear();
	}

	/** Finishes the current pointer sequence while retaining click suppression state. */
	private finish(): void {
		if (
			this.pointerId !== undefined &&
			this.operation
		) {
			this.callbacks.onDragEnd(
				this.pointerId
			);
		}

		this.pointerId = undefined;
		this.startPoint = undefined;
		this.lastPoint = undefined;
		this.operation = undefined;
		this.visitedTargets.clear();
	}

	/** Interpolates a pointer segment so fast movement does not skip short words. */
	private processSegment(
		from: PointerPoint,
		to: PointerPoint
	): void {
		if (!this.operation) {
			return;
		}

		const distance = Math.hypot(
			to.x - from.x,
			to.y - from.y
		);
		const steps = Math.min(
			MAX_INTERPOLATION_STEPS,
			Math.max(
				1,
				Math.ceil(
					distance /
						INTERPOLATION_DISTANCE_PX
				)
			)
		);

		for (
			let step = 0;
			step <= steps;
			step += 1
		) {
			const ratio = step / steps;
			this.processPoint({
				x: from.x + (to.x - from.x) * ratio,
				y: from.y + (to.y - from.y) * ratio
			});
		}
	}

	/** Resolves and mutates one not-yet-visited semantic token under the stroke. */
	private processPoint(point: PointerPoint): void {
		const target =
			this.callbacks.resolveTarget(point);

		if (!target || target.wordIndex < 0) {
			return;
		}

		const key =
			`${target.verseNumber}:${target.wordIndex}`;

		if (this.visitedTargets.has(key)) {
			return;
		}

		this.visitedTargets.add(key);

		if (this.operation === 'apply') {
			this.callbacks.onApply(target);
			return;
		}

		this.callbacks.onRemove(target);
	}
}
